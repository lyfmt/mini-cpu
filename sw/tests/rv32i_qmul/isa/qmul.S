// 单指令测试：qmul（定制指令，设计文档第七节）
//
//   qmul rd, rs1, rs2    rd <- (rs1[11:0] × rs2[11:0]) mod 3329，操作数按无符号数
//
// 期望值按定义算（q = 3329）：
//   0·0 = 0；0·3328 = 0；1·1 = 1；1·3328 = 3328
//   (q−1)² ≡ (−1)² = 1
//   4095·4095：4095 ≡ 766，766² = 586756 = 176·3329 + 852       -> 852
//   4095·1 = 4095 = 3329 + 766                                   -> 766
//   3329·5 ≡ 0；3330·3330 ≡ 1·1 = 1
//   1234·2345 = 2893730 = 869·3329 + 829                         -> 829
//   0x800·0x7ff = 2048·2047 = 4192256 = 1259·3329 + 1045         -> 1045
//     （按有符号数算会是 −2048·2047 ≡ 2284，用来区分"无符号"）
//   只取低 12 位：
//     0xfffff001 · 0x12345678 -> 1 · 0x678 = 1656
//     0x12345678 · 0xfffff001 -> 0x678 · 1 = 1656
//     0xabcdef12 · 0x87654fff -> 0xf12 · 0xfff = 3858·4095 = 15798510
//                                = 4745·3329 + 2405                -> 2405
//     0x00001000 · 0x000007ff -> 0 · 2047 = 0（第 12 位不参与）
//   2000·2000 = 4000000 = 1201·3329 + 1871                       -> 1871
//
// 每项先把目的寄存器装成 0x5a5a5a5a，以免旧值碰巧等于期望值。
//
// 失败码：
//   1  0 · 0 = 0               9  3329 · 5 = 0
//   2  0 · 3328 = 0           10  3330 · 3330 = 1
//   3  1 · 1 = 1              11  1234 · 2345 = 829
//   4  1 · 3328 = 3328        12  0x800 · 0x7ff = 1045（无符号）
//   5  3328 · 1 = 3328        13  0xfffff001 · 0x12345678 = 1656（rs1 高位不参与）
//   6  (q−1)² = 1             14  0x12345678 · 0xfffff001 = 1656（rs2 高位不参与）
//   7  4095 · 4095 = 852      15  0xabcdef12 · 0x87654fff = 2405（两边高位都不参与）
//   8  4095 · 1 = 766         16  0x1000 · 0x7ff = 0（第 12 位不参与）
//  17  rd = x0：x0 仍为 0，之后读 x0 得 0
//  18  rd = rs1：qmul x5, x5, x6 = 829
//  19  rd = rs2：qmul x6, x5, x6 = 829
//  20  rs1 = rs2：qmul x9, x8, x8 = 2000² mod q = 1871，x8 不变
//  21  rd = rs1 = rs2：qmul x11, x11, x11 = 3328² mod q = 1
#include "test.h"
#include "qmul.h"

// x10 <- qmul(a, b)，检查等于 expect。x5、x6 放操作数，x7 是 LI 的临时寄存器。
.macro QCASE a, b, expect, code
    LI      x5, \a, x7
    LI      x6, \b, x7
    LI      x10, 0x5a5a5a5a, x7
    PAD_DATA
    qmul    x10, x5, x6
    CHECK   x10, \expect, \code
.endm

TEST_BEGIN
    QCASE   0, 0, 0, 1
    QCASE   0, 3328, 0, 2
    QCASE   1, 1, 1, 3
    QCASE   1, 3328, 3328, 4
    QCASE   3328, 1, 3328, 5
    QCASE   3328, 3328, 1, 6
    QCASE   4095, 4095, 852, 7
    QCASE   4095, 1, 766, 8
    QCASE   3329, 5, 0, 9
    QCASE   3330, 3330, 1, 10
    QCASE   1234, 2345, 829, 11
    QCASE   0x800, 0x7ff, 1045, 12
    QCASE   0xfffff001, 0x12345678, 1656, 13
    QCASE   0x12345678, 0xfffff001, 1656, 14
    QCASE   0xabcdef12, 0x87654fff, 2405, 15
    QCASE   0x1000, 0x7ff, 0, 16

    // rd = x0
    LI      x5, 1234
    LI      x6, 2345, x7
    PAD_DATA
    qmul    x0, x5, x6
    PAD_DATA
    add     x12, x0, x0
    CHECK   x0, 0, 17
    CHECK   x12, 0, 17

    // rd = rs1、rd = rs2（x5、x6 仍是 1234、2345）
    qmul    x5, x5, x6
    CHECK   x5, 829, 18
    LI      x5, 1234
    PAD_DATA
    qmul    x6, x5, x6
    CHECK   x6, 829, 19

    // rs1 = rs2
    LI      x8, 2000
    LI      x9, 0x5a5a5a5a, x7
    PAD_DATA
    qmul    x9, x8, x8
    CHECK   x9, 1871, 20
    CHECK   x8, 2000, 20

    // rd = rs1 = rs2
    LI      x11, 3328, x7
    PAD_DATA
    qmul    x11, x11, x11
    CHECK   x11, 1, 21
TEST_END
